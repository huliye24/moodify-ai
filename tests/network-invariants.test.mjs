import { test } from "node:test";
import assert from "node:assert/strict";
import {
  NetworkObservatory,
} from "../apps/web/lib/mood/network/observatory.ts";
import { contributionRegistry } from "../apps/web/lib/mood/contribution/registry.ts";

function freshObservatory() {
  return new NetworkObservatory();
}

function seedContributionData() {
  const t = contributionRegistry.createTask({
    slug: "t-network",
    title: "Network task",
    summary: "Test",
    description: "Test",
    category: "code",
    evidenceRequirements: [],
    defaultReputationPoints: 10,
    defaultRewardUnits: "5u",
    createdByResidentId: "system",
  });
  const s1 = contributionRegistry.createSubmission({
    taskId: t.id,
    residentId: "resident_alpha",
    summary: "First approved contribution.",
    evidenceItems: [{ type: "url", value: "https://example.com/1" }],
  });
  const s2 = contributionRegistry.createSubmission({
    taskId: t.id,
    residentId: "resident_beta",
    summary: "Second approved contribution.",
    evidenceItems: [{ type: "url", value: "https://example.com/2" }],
  });
  contributionRegistry.review({
    submissionId: s1.id,
    decision: "approve",
    reviewerResidentId: "reviewer_x",
  });
  contributionRegistry.review({
    submissionId: s2.id,
    decision: "approve",
    reviewerResidentId: "reviewer_y",
  });
}

// ??? INV-017-01 ???????????????????????????????????????????????????????????????

test("INV-017-01: /network route renders (overview API returns JSON)", () => {
  const obs = freshObservatory();
  const o = obs.overview();
  assert.equal(typeof o.status, "string");
  assert.equal(typeof o.generatedAt, "string");
  assert.ok(o.metrics);
});

// ??? INV-017-02 ???????????????????????????????????????????????????????????????

test("INV-017-02: all public numbers have real source", () => {
  seedContributionData();
  const o = freshObservatory().overview();
  for (const [k, m] of Object.entries(o.metrics)) {
    if (!m) continue;
    assert.ok(m.source && m.source.length > 0, k + " missing source");
    assert.ok(m.definition && m.definition.length > 0, k + " missing definition");
  }
});

