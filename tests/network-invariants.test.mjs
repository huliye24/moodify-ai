// ??? INV-017-04 ???????????????????????????????????????????????????????????????

test("INV-017-04: Residents count sourced from distinct residentIds (not wallets)", () => {
  const m = freshObservatory().residents();
  // Either the metric is real (source mentions residentIds) or suppressed
  // (state=unavailable). Either way, Residents are never wallet count.
  assert.ok(m.source.length > 0);
  if (m.state === "available") {
    assert.match(m.source, /residentIds/);
  } else {
    assert.equal(m.state, "unavailable");
  }
});

// ??? INV-017-05 ???????????????????????????????????????????????????????????????

test("INV-017-05: private reviewer notes not in activity feed", () => {
  const reg = contributionRegistry;
  const task = reg.createTask({
    slug: "t-private",
    title: "T",
    summary: "Test task",
    description: "Test",
    category: "code",
    evidenceRequirements: [],
    defaultReputationPoints: 5,
    createdByResidentId: "system",
  });
  const sub = reg.createSubmission({
    taskId: task.id,
    residentId: "resident_zzz",
    summary: "Private note leak test.",
    evidenceItems: [{ type: "url", value: "https://example.com/x" }],
  });
  reg.review({
    submissionId: sub.id,
    decision: "request-changes",
    reviewerResidentId: "reviewer_z",
    note: "PRIVATE-INTERNAL-NOTE-FOR-REVIEWER-EYES-ONLY-XYZ",
  });
  const feed = freshObservatory().activity(50);
  const serialized = JSON.stringify(feed);
  assert.equal(serialized.includes("PRIVATE-INTERNAL-NOTE"), false);
});

