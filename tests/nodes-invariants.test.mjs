import { test } from "node:test";
import assert from "node:assert/strict";
import {
  NodeRegistry,
  nodeRegistry,
} from "../apps/web/lib/mood/nodes/index.ts";
import { agentRegistry } from "../apps/web/lib/mood/agents/registry.ts";
import { NetworkObservatory } from "../apps/web/lib/mood/network/observatory.ts";

const RESIDENT_OP = "resident_node_operator";
const RESIDENT_OTHER = "resident_other";

function fresh() {
  return new NodeRegistry();
}

function seedBasic(reg = fresh()) {
  const n = reg.register({
    slug: "compute-001",
    name: "Compute Node 001",
    role: "compute",
    capabilities: ["batch-jobs", "audio-processing"],
    operatorResidentId: RESIDENT_OP,
    publicRegion: "Asia Pacific",
    version: "1.0.0",
    capacity: { cpuCores: 16, memoryGb: 32, storageGb: 1000 },
    publicEndpoint: "https://node-001.example.com",
  });
  reg.activate(n.id, RESIDENT_OP);
  return n;
}

// ??? INV-019-01 ???????????????????????????????????????????????????????????????

test("INV-019-01: every active Node has stable ID", () => {
  const reg = fresh();
  const n = seedBasic(reg);
  assert.equal(typeof n.id, "string");
  assert.ok(n.id.startsWith("node_"));
  const again = reg.requireNode(n.id);
  assert.equal(again.id, n.id);
});

