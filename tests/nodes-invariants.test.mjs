// ??? INV-019-05 ???????????????????????????????????????????????????????????????

test("INV-019-05: public API does not leak private infra details", () => {
  const reg = fresh();
  const n = seedBasic(reg);
  reg.recordHeartbeat({
    nodeId: n.id,
    observedAt: new Date().toISOString(),
    status: "ok",
  });
  const pub = reg.publicBySlug(n.slug);
  assert.ok(pub);
  const json = JSON.stringify(pub);
  // Should not contain SSH / cloud account patterns.
  assert.equal(json.includes("ssh"), false);
  assert.equal(json.includes("AKIA"), false); // AWS access key prefix
  // Should not contain operatorResidentId raw value.
  const pubTyped = pub;
  assert.equal(pubTyped.operatorResidentId, undefined);
  assert.equal(pubTyped.operatorOrganizationId, undefined);
  assert.equal(pubTyped.healthSummary, undefined);
  // publicEndpoint should be the safe URL (allowed to appear).
  assert.match(json, /node-001\.example\.com/);
});

