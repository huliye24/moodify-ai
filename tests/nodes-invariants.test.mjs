// ??? INV-019-09 ???????????????????????????????????????????????????????????????

test("INV-019-09: Agent and Node data models are separate", () => {
  // Two distinct registries with distinct IDs and record shapes.
  const agent = agentRegistry.register({
    slug: "agent-x",
    name: "Agent X",
    description: "X",
    capabilities: ["research"],
    operatorResidentId: RESIDENT_OP,
    public: true,
  });
  const node = nodeRegistry.register({
    slug: "node-x",
    name: "Node X",
    role: "compute",
    capabilities: ["batch-jobs"],
    operatorResidentId: RESIDENT_OP,
  });
  assert.notEqual(agent.id, node.id);
  assert.ok(agent.id.startsWith("agent_"));
  assert.ok(node.id.startsWith("node_"));
  // Cross-method tests
  const methodsAgent = Object.getOwnPropertyNames(Object.getPrototypeOf(agentRegistry));
  const methodsNode = Object.getOwnPropertyNames(Object.getPrototypeOf(nodeRegistry));
  // Node registry must NOT have agent-only methods like "recordProof" with taskType proofType.
  assert.ok(!methodsNode.includes("startTaskRun"));
});

